'use strict';

// TensorBoard 2.21.0 reads these preferences before starting its browser timer.
// Initialize only an absent choice; an explicit user setting always wins.
(() => {
  try {
    const storage=window.localStorage, key='_tb_global_settings';
    const read=name=>{
      const value=storage.getItem(name);
      if(value===null)return {};
      const parsed=JSON.parse(value);
      if(!parsed || typeof parsed!=='object' || Array.isArray(parsed))throw new Error('Invalid settings');
      return parsed;
    };
    const legacy=read('_tb_global_settings.timeseries'), current=read(key);
    if(!Object.hasOwn(legacy,'autoReload') && !Object.hasOwn(current,'autoReload'))storage.setItem(key,JSON.stringify({...current,autoReload:true}));
  } catch (_) {
    // Disabled storage or malformed user settings do not block TensorBoard.
  }
})();

// Scope lives in this page and its requests, never in shared cookies/storage.
// Installed before TensorBoard boots: legacy Scalars and modern Time Series
// both need scoped metadata, not merely a selected checkbox or tag regex.
(() => {
  if(!window.location)return;
  const page=new URL(window.location.href),parameter='dashboard_task';
  const basePath=page.pathname.split('/tensorboard',1)[0];
  let scope=page.searchParams.get(parameter);
  if(scope===null){
    // Upgrade links generated by earlier dashboard versions. Arbitrary user
    // regexes remain ordinary global TensorBoard filters.
    const filter=new URLSearchParams(page.hash.slice(1)).get('runFilter')||'';
    const match=filter.match(/^\^(active|history-[1-9][0-9]*)\/(#([0-9]{4,})|long\/(L[0-9a-f]{16})|manual\/([A-Za-z0-9][A-Za-z0-9_-]{0,63})\/)/);
    if(match){
      const rest=filter.slice(match[0].length);
      if(match[5]?rest==='':rest==='$'||rest==='(?:$| \\(attempt [0-9]+\\)|/)'){
        scope=JSON.stringify({source:match[1],...(match[3]?{experiment:match[3]}:match[4]?{run:match[4]}:{task:match[5]})});
      }
    }
  }
  const scopedURL=value=>{
    if(!basePath && scope===null)return value;
    const url=new URL(String(value),page);
    if(url.origin!==page.origin)return value;
    const path=basePath && url.pathname.startsWith(basePath+'/')?url.pathname.slice(basePath.length):url.pathname;
    if(!path.startsWith('/tensorboard/'))return value;
    url.pathname=basePath+path;
    if(scope!==null && /^\/tensorboard(?:\/experiment\/[^/]*)?\/data\//.test(path))url.searchParams.set(parameter,scope);
    return url.href;
  };
  if(window.fetch){
    const original=window.fetch;
    window.fetch=function(input,init){
      if(typeof window.Request!=='undefined' && input instanceof window.Request){
        const url=scopedURL(input.url);
        return original.call(this,url===input.url?input:new window.Request(url,input),init);
      }
      return original.call(this,scopedURL(input),init);
    };
  }
  if(window.XMLHttpRequest){
    const original=window.XMLHttpRequest.prototype.open;
    window.XMLHttpRequest.prototype.open=function(method,url,...args){return original.call(this,method,scopedURL(url),...args);};
  }
  if(typeof document==='undefined')return;
  document.addEventListener('click',event=>{
    const anchor=event.target.closest?.('a[href]');
    if(anchor)anchor.href=scopedURL(anchor.href);
  },true);
  if(scope===null)return;
  const banner=()=>{
    const bar=document.createElement('div');bar.id='dashboard-task-scope';
    bar.style.cssText='position:fixed;bottom:0;left:0;right:0;z-index:2147483647;background:#183c39;color:#e4fff5;padding:7px 14px;font:13px system-ui;display:flex;gap:16px;justify-content:space-between';
    const label=document.createElement('span');
    try{const task=JSON.parse(scope);label.textContent='任务指标：'+task.source+' · '+(task.task||task.run||'#'+task.experiment);}
    catch(_){label.textContent='任务筛选无效，请从任务看板重新打开。';}
    const all=document.createElement('a');all.href=basePath+'/tensorboard/#scalars';all.textContent='查看所有任务';all.style.color='#9ce8d0';
    bar.append(label,all);document.body.append(bar);
  };
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',banner,{once:true});else banner();
})();
